"""Train a Random Forest on summaries of the same VNAT packet prefixes."""

import argparse
from pathlib import Path

import joblib
import numpy as np
from sklearn.ensemble import RandomForestClassifier

from traffic_classifier.ml.dataset import DEFAULT_BUNDLE, Bundle, load_bundle
from traffic_classifier.ml.vnat_split import DEFAULT_MANIFEST, SEED
from traffic_classifier.vnat_groups import CLASSES, PREFIX_LENGTHS

DEFAULT_DIR = Path("artifacts/random-forest-v1")
FEATURE_NAMES = (
    "observed_packets",
    "same_direction_fraction",
    "size_mean",
    "size_std",
    "size_min",
    "size_max",
    "gap_mean",
    "gap_std",
    "gap_min",
    "gap_max",
)
PARAMETERS = {
    "n_estimators": 120,
    "max_depth": 12,
    "min_samples_leaf": 2,
    "class_weight": "balanced_subsample",
    "random_state": SEED,
    "n_jobs": 2,
}


def summarize_prefixes(bundle: Bundle, n: int) -> np.ndarray:
    if n not in PREFIX_LENGTHS:
        raise ValueError(f"Unsupported N: {n}")
    x = bundle.features[:, :, :n].astype(np.float64)
    mask = bundle.mask[:, :n]
    count = mask.sum(axis=1)
    if np.any(count == 0):
        raise ValueError("Every prefix must contain an observed packet.")
    features = [count, np.where(mask, x[:, 1], 0).sum(axis=1) / count]
    for channel in (0, 2):
        values = x[:, channel]
        mean = np.where(mask, values, 0).sum(axis=1) / count
        std = np.sqrt(np.where(mask, (values - mean[:, None]) ** 2, 0).sum(axis=1) / count)
        features.extend(
            [
                mean,
                std,
                np.where(mask, values, np.inf).min(axis=1),
                np.where(mask, values, -np.inf).max(axis=1),
            ]
        )
    return np.column_stack(features)


def train_forest(train: Bundle, n: int) -> dict:
    if train.split != "train":
        raise ValueError("The Random Forest is fitted only on train.")
    if tuple(np.unique(train.labels)) != tuple(range(len(CLASSES))):
        raise ValueError("The training split does not cover every class.")
    estimator = RandomForestClassifier(**PARAMETERS)
    estimator.fit(summarize_prefixes(train, n), train.labels)
    return {
        "estimator": estimator,
        "version": 1,
        "n": n,
        "parameters": PARAMETERS.copy(),
        "import_id": train.import_id,
        "manifest_sha256": train.manifest_sha256,
        "feature_names": FEATURE_NAMES,
        "classes": CLASSES,
    }


def load_forest(path: Path, bundle: Bundle, n: int) -> dict:
    # Model files are local artifacts generated by train_forest().
    artifact = joblib.load(path)
    expected = (1, n, bundle.import_id, bundle.manifest_sha256, FEATURE_NAMES, CLASSES)
    actual = tuple(
        artifact[key]
        for key in (
            "version",
            "n",
            "import_id",
            "manifest_sha256",
            "feature_names",
            "classes",
        )
    )
    if actual != expected:
        raise ValueError("Forest artifact does not match the requested data and prefix.")
    return artifact


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--n", type=int, choices=PREFIX_LENGTHS, default=32)
    parser.add_argument("--packages", type=Path, default=DEFAULT_BUNDLE)
    parser.add_argument("--manifest", type=Path, default=DEFAULT_MANIFEST)
    parser.add_argument("--output", type=Path, default=DEFAULT_DIR)
    args = parser.parse_args()

    train = load_bundle(args.packages, "train", args.manifest)
    artifact = train_forest(train, args.n)
    path = args.output / f"n{args.n}.joblib"
    path.parent.mkdir(parents=True, exist_ok=True)
    joblib.dump(artifact, path, compress=3)
    print(f"N={args.n}: {len(train.labels)} train flows and {len(FEATURE_NAMES)} features; {path}")


if __name__ == "__main__":
    main()
